def _juger(tmp_path, fichiers: dict[str, str]):
    for nom, texte in fichiers.items():
        p = tmp_path / nom
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(texte, encoding="utf-8")
    return juges_sql.juger(tmp_path, list(fichiers))


