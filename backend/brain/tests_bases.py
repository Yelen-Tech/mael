def _projet_cassandra(tmp_path, schema):
    (tmp_path / "db" / "cql").mkdir(parents=True)
    (tmp_path / "app.py").write_text("from cassandra.cluster import Cluster\n")
    (tmp_path / "db" / "schema.cql").write_text(schema, encoding="utf-8")
    (tmp_path / "db" / "cql" / "ventes.cql").write_text(
        "INSERT INTO ventes (id, montant) VALUES (1, 500);", encoding="utf-8")
