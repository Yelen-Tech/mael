def _projet(tmp_path, demande, fichiers):
    e = Espace(tmp_path / "projet")
    log = Logistique(e, demande)
    log.adresser(list(fichiers))
    for chemin, texte in fichiers.items():
        e.ecrire(arbo.ranger(chemin, log.sorte), texte)
    log.finir()
    return tmp_path / "projet"


def test_api_flask_postgres_complete(tmp_path):
    r = _projet(tmp_path, "une API Flask de commandes avec PostgreSQL", {
        "app.py": "import os\nimport psycopg\nfrom flask import Flask\n"
                  "app = Flask(__name__)\n"
                  "DB = os.environ.get('DATABASE_URL')\n",
        "schema.sql": "CREATE TABLE clients (id BIGSERIAL PRIMARY KEY, "
                      "nom TEXT NOT NULL);"})
    assert (r / "db/schema.sql").exists() and (r / "app/main.py").exists()
    assert (r / "requirements.txt").read_text().split() == [
        "flask", "psycopg[binary]"]
    env = (r / ".env.example").read_text()
    assert "DATABASE_URL=postgresql://app:changer-moi@localhost:5432/app" in env
    compose = (r / "docker-compose.yml").read_text()
    assert "image: postgres:16-alpine" in compose and '"5432:5432"' in compose
    assert "postgres-donnees:/var/lib/postgresql/data" in compose
    readme = (r / "README.md").read_text(encoding="utf-8")
    assert "## Base de donnees" in readme and "**PostgreSQL**" in readme
    assert 'psql "$DATABASE_URL" -f db/schema.sql' in readme
    assert "docker compose up -d" in readme


