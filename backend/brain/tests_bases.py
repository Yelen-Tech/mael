SCHEMA = """
CREATE TABLE clients (id INTEGER PRIMARY KEY, nom TEXT NOT NULL,
                      telephone TEXT UNIQUE);
CREATE TABLE commandes (id INTEGER PRIMARY KEY,
                        client_id INTEGER NOT NULL REFERENCES clients(id),
                        montant INTEGER NOT NULL);
"""


@pytest.mark.parametrize("fichier,code,attendus", [
    # Python, juste : alias, jointure, fonction, parametres %s et ?
    ("app/main.py", 'db.execute("SELECT c.nom, SUM(k.montant) AS total '
     'FROM clients c JOIN commandes k ON k.client_id = c.id GROUP BY c.nom '
     'ORDER BY total")\ndb.execute("UPDATE clients SET nom = %s WHERE id = '
     '%s", (n, i))', []),
    # Python, faux : table et colonne
    ("app/main.py", 'db.execute("INSERT INTO client (nom) VALUES (?)", x)\n'
     'db.execute("UPDATE commandes SET statut = ? WHERE id = ?", x)',
     ["sql-table-inconnue", "sql-colonne-inconnue"]),
    # JavaScript : gabarit ${} et $1 (pg)
    ("src/db.js", 'pool.query(`SELECT nom FROM clients WHERE id = ${id}`);\n'
     'pool.query("DELETE FROM commandes WHERE ref = $1", [r]);',
     ["sql-colonne-inconnue"]),
    # PHP : requete preparee
    ("index.php", '<?php $s = $pdo->prepare("SELECT telephone FROM clients '
     'WHERE nom = :nom");', []),
    # une requete EN MORCEAUX n'est pas jugee (illisible seule, pas fausse)
    ("app/main.py", 'db.execute("SELECT * FROM " + table)', []),
    # CTE : le nom de la CTE n'est pas une table du schema
    ("app/main.py", 'db.execute("WITH gros AS (SELECT client_id FROM '
     'commandes WHERE montant > 5000) SELECT nom FROM clients WHERE id IN '
     '(SELECT client_id FROM gros)")', []),
])
def test_le_code_et_le_schema(tmp_path, fichier, code, attendus):
    d = _juger(tmp_path, {"db/schema.sql": SCHEMA, fichier: code})
