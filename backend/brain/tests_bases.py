SCHEMA_SQLA = """
CREATE TABLE clients (id INTEGER PRIMARY KEY, nom TEXT NOT NULL, tel TEXT);
CREATE TABLE commandes (id INTEGER PRIMARY KEY,
                        client_id INTEGER REFERENCES clients(id),
                        montant INTEGER NOT NULL);
"""


